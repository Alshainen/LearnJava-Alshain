package Arithmetic;

public class Arithmetic {
    public static void main(String[] args) {
        int a = 100;
        int b = 20;

        // Penjumlahan
        System.out.println(a + b);

        // Tambah 1 aja atau selalu tambah 1
        System.out.println(a++);

        // Pengurangan
        System.out.println(a - b);

        // Kurang 1 aja atau selalu kurang 1
        System.out.println(a--);

        // Perkalian
        System.out.println(a * b);

        // Pembagian
        System.out.println(a / b);

        // Modulus atau Sisa bagi
        System.out.println(a % b);
    }
}
